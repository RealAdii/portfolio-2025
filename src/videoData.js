// Extract thumbnail URL from video URL
export function getThumbnailUrl(url) {
  // YouTube
  const youtubeMatch = url.match(/(?:youtube\.com\/watch\?v=|youtu\.be\/)([a-zA-Z0-9_-]{11})/)
  if (youtubeMatch) {
    return `https://img.youtube.com/vi/${youtubeMatch[1]}/mqdefault.jpg`
  }

  // X/Twitter - extract tweet ID for embed card
  const twitterMatch = url.match(/(?:twitter\.com|x\.com)\/\w+\/status\/(\d+)/)
  if (twitterMatch) {
    // Use a placeholder with the platform icon for X/Twitter
    // Twitter doesn't expose thumbnails directly, so we'll use a styled card
    return null // Will use fallback styling
  }

  return null
}

// Check if URL is from X/Twitter
export function isTwitterUrl(url) {
  return url.includes('x.com') || url.includes('twitter.com')
}

// Check if URL is from YouTube
export function isYouTubeUrl(url) {
  return url.includes('youtube.com') || url.includes('youtu.be')
}
